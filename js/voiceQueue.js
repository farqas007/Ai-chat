export class VoiceQueue {

    constructor() {

        this.queue = [];

        this.playing = false;

        console.log(
            "Voice Queue Created"
        );

    }

    /* =======================================================
       ADD
    ======================================================= */

    add(item) {

        this.queue.push(item);

    }

    /* =======================================================
       NEXT
    ======================================================= */

    next() {

        return this.queue.shift();

    }

    /* =======================================================
       HAS ITEMS
    ======================================================= */

    hasItems() {

        return this.queue.length > 0;

    }

    /* =======================================================
       CLEAR
    ======================================================= */

    clear() {

        this.queue.length = 0;

    }

    /* =======================================================
       SIZE
    ======================================================= */

    size() {

        return this.queue.length;

    }

}